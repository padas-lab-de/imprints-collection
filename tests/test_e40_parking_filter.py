import gzip
import importlib.util
import io
import json
from collections import Counter
from pathlib import Path

_root = Path(__file__).resolve().parents[1] / "scripts/E40"
spec = importlib.util.spec_from_file_location("parking_filter", _root / "parking_filter.py")
pf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pf)


def cat(title, content, desc=""):
    r = pf.detect(title, desc, content)
    return r[0] if r else None


def test_for_sale_pages():
    assert cat("x.de", "Diese Domain steht zum Verkauf. Bei Interesse senden Sie uns eine Mail.") == "sale"
    assert cat("", "This domain may be for sale. Find information about it.") == "sale"
    assert cat("", "Die Premium-Domain abc.de ist auf fruits.co verfügbar.") == "sale"
    assert cat("HugeDomains.com", "HugeDomains.com Captcha security check") == "sale"


def test_parked_and_registrar_placeholders():
    assert cat("", "Namecheap Logo Domain registration has expired. Renewal instructions") == "park"
    assert cat("STRATO - Domain not available", "STRATO English This website is currently not available.") == "park"
    assert cat("Domain geparkt", "easyname GmbH") == "park"


def test_hosting_and_construction_are_not_core():
    assert cat("Web Server's Default Page", "This page is generated by Plesk") == "host"
    assert cat("", "Hier entsteht eine neue Internetpräsenz") == "constr"
    assert "host" not in pf.CORE and "constr" not in pf.CORE


def test_real_sites_not_flagged():
    text = "Wir bieten Elektrotechnik seit 1990. Kontakt Impressum Datenschutz. " * 5
    assert cat("Elektro Meier", text) is None
    assert cat("Autohaus", "Gebrauchtwagen zu verkaufen: Golf, Polo. Hier finden Sie unsere Angebote.") is None


def test_weak_pattern_ignored_on_long_pages_strong_not():
    filler = "Lorem ipsum dolor sit amet. " * 200  # > WEAK_MAX chars
    assert cat("Shop", "Domain kaufen " + filler) is None
    assert cat("Shop", "Diese Domain steht zum Verkauf. " + filler) == "sale"


def test_most_severe_category_wins():
    assert cat("", "Coming soon. Diese Domain steht zum Verkauf.") == "sale"


def test_site_flags_rules():
    canon = {"a.de": ["a.de", "www.a.de"], "b.de": ["b.de", "x.b.de"], "ts.park.de": ["h1.de", "h2.de"], "c.de": []}
    host_cat = {"a.de": "park", "www.a.de": "sale", "b.de": "park", "x.b.de": None}
    out = pf.site_flags(canon, host_cat, {"ts.park.de": "sale"})
    assert out == {"a.de": "sale", "ts.park.de": "sale"}  # b.de has an unflagged host; c.de has no found host


def test_host_category_uses_text_then_target():
    flagged = {"h.de": ("park", "parked", "u", "t", "c")}
    tc = {"ts.park.de": "sale"}
    assert pf.host_category("h.de", "", flagged, tc) == "park"
    assert pf.host_category("g.de", "www.ts.park.de", flagged, tc) == "sale"
    assert pf.host_category("g.de", "real.de", flagged, tc) is None


def test_load_targets_keeps_parking_classes(tmp_path):
    p = tmp_path / "t.tsv"
    p.write_text("target\thosts\tclass\nts.park.de\t5\tdomain_sale\nvw.de\t9\treal\ndenic.de\t3\tregistry\n")
    assert pf.load_targets(p) == {"ts.park.de": "sale", "denic.de": "park"}


def test_wilson():
    lo, hi = pf.wilson(58, 60)
    assert 0.88 < lo < 0.89 and 0.99 < hi < 1.0
    assert pf.wilson(0, 0) == (0.0, 0.0)


def test_scan_dir_last_record_wins_and_sample_rows(tmp_path):
    def rec(h, title, content):
        return json.dumps({"host": h, "main": {"url": f"https://{h}", "title": title, "main_content": content}}) + "\n"

    with gzip.open(tmp_path / "imprints_batch000000.jsonl.gz", "wt") as f:
        f.write(rec("a.de", "", "Diese Domain steht zum Verkauf."))
        f.write(rec("b.de", "", "Diese Domain steht zum Verkauf."))
        f.write(rec("target.de", "Real", "Echte Firma mit viel Inhalt"))
    with gzip.open(tmp_path / "imprints_batch000001.jsonl.gz", "wt") as f:
        f.write(rec("a.de", "Echte Firma", "Wir sind ein Unternehmen."))  # resume duplicate, now unflagged
    buf, st = io.StringIO(), Counter()
    pf.scan_dir(str(tmp_path), {"target.de"}, buf, st)
    rows = [l.split("\t") for l in buf.getvalue().splitlines()]
    flagged = {r[0] for r in rows if r[1] == "F"}
    assert flagged == {"b.de"}
    assert [r[0] for r in rows if r[1] == "T"] == ["target.de"]
    assert st["records"] == 4 and st["flagged"] == 1
    fl, _, tg = pf.load_scan([_write(tmp_path, buf.getvalue())])
    assert fl["b.de"][0] == "sale" and "target.de" in tg


def test_real_target_overrides_text_flag(tmp_path):
    p = tmp_path / "t.tsv"
    p.write_text("target\thosts\tclass\nwebrobots.de\t9\treal\nts.park.de\t5\tdomain_sale\n")
    real = pf.load_real_targets(p)
    assert real == {"webrobots.de"}
    flagged = {
        "h.de": ("sale", "broker_brand", "https://webrobots.de/", "t", "c"),
        "g.de": ("sale", "x", "https://g.de/", "t", "c"),
    }
    assert pf.host_category("h.de", "webrobots.de", flagged, {}, real) is None
    assert pf.host_category("g.de", "", flagged, {}, real) == "sale"


def _write(d, text):
    p = d / "scan.tsv"
    p.write_text(text)
    return p
